name = input("Enter your message: ")

if name == "hello":
    print("Hello to you too!")
elif name == "bye":
    print("Goodbye!")
elif name == "help":
    print("How can I assist you?")
elif name == "thanks":
    print("You're welcome!")
elif name == "yes":
    print("Great!")
elif name == "what is python":
    print("Python is a programming language.")
else:
    print("I don't understand that.")
